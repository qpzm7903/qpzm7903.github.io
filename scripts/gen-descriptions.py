#!/usr/bin/env python3
"""P3: 为缺少 description 的文章生成可用的摘要（写回 front matter）。

为什么不用模板自动截取：PaperMod 的 fallback 是 `.Summary`（正文前 ~70 词），
对本站会产出 "📰 科技热点日报 | 2026-06-03 Generated by OpenClaw v3" 这类垃圾摘要
（基线：366 篇里只有 9 篇有 description）。

生成规则（按内容家族，优先级从高到低）：
  1. front matter 已有 description → 不动
  2. `daily-*`（话题日报）      → 「📌 今日判断」小节第一段
  3. `*-update-*`（连载）        → 「## ✨ 新增功能」等首个功能小节的第一条
  4. `weekly-review-*`（周报）   → 开头的 `>` 导语
  5. 其余（手写长文）            → 首个 ≥20 字的正文段落（跳过 H1 / 短标签行 / 引用）
  6. 兜底                       → 标题 + 「见正文」

所有候选都会过三道滤镜：
  * 剔除跨文章高频出现的模板句（≥5% 文章出现即视为 boilerplate）
  * 剔除 markdown 残留（链接语法、图片、强调符号、HTML 标签）
  * 长度收缩到 40~120 字，尽量在句读处截断

用法：
    python3 scripts/gen-descriptions.py                  # dry-run + 抽样
    python3 scripts/gen-descriptions.py --apply          # 写回
    python3 scripts/gen-descriptions.py --apply --only-empty   # 只补空，不覆盖已有的
"""

from __future__ import annotations

import argparse
import collections
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
POSTS = ROOT / "content" / "posts"

TARGET_MIN, TARGET_MAX = 40, 120
BOILERPLATE_RATIO = 0.05

FM_RE = re.compile(r"^---\n(.*?)\n---\n", re.S)
HEADING_RE = re.compile(r"^#{1,6}\s+")
FENCE_RE = re.compile(r"```.*?```", re.S)
IMG_RE = re.compile(r"!\[[^\]]*\]\([^)]*\)")
LINK_RE = re.compile(r"\[([^\]]*)\]\([^)]*\)")
HTML_RE = re.compile(r"<[^>]+>")
EMPH_RE = re.compile(r"(\*\*|__|\*|`)(.+?)\1")
BULLET_RE = re.compile(r"^\s*[-*+]\s+")
QUOTE_RE = re.compile(r"^>\s?")
SENT_SPLIT = re.compile(r"(?<=[。！？；])")
LABEL_RE = re.compile(r"^\*{0,2}[^*：:]{1,12}\*{0,2}\s*[:：]")


def clean(text: str) -> str:
    text = IMG_RE.sub("", text)
    text = LINK_RE.sub(r"\1", text)
    text = HTML_RE.sub("", text)
    text = EMPH_RE.sub(r"\2", text)
    text = text.replace("`", "")
    text = re.sub(r"\s+", " ", text).strip()
    return text


def paragraphs(body: str) -> list[str]:
    body = FENCE_RE.sub("", body)
    out = []
    for raw in body.split("\n"):
        line = raw.rstrip()
        if not line.strip():
            out.append("")  # 段落分隔
            continue
        quote = False
        while QUOTE_RE.match(line):
            line = QUOTE_RE.sub("", line, count=1)
            quote = True
        line = BULLET_RE.sub("", line)
        out.append(clean(line))
    return out


def section_text(body: str, heading_keyword: str) -> str:
    """取某个标题下的第一段正文（到下一个标题为止）。"""
    lines = body.split("\n")
    capture = False
    buf: list[str] = []
    for line in lines:
        if HEADING_RE.match(line):
            if capture and buf:
                break
            capture = heading_keyword in line
            continue
        if capture:
            buf.append(line)
    return "\n".join(buf)


def pick_candidate(path: Path, body: str, freq: collections.Counter, title: str = "") -> tuple[str, str]:
    name = path.name
    cand, rule = "", "fallback"

    if name.startswith("daily-"):
        # 日报里「今日判断」常是模板句，优先用「最值得关注」里当天的具体条目
        cand, rule = section_text(body, "最值得关注"), "最值得关注"
        if not cand.strip():
            cand, rule = section_text(body, "今日判断"), "今日判断"
    elif re.search(r"-update-", name):
        for kw in ("新增", "功能", "变更", "修复"):
            cand = section_text(body, kw)
            if cand.strip():
                rule = f"更新小节:{kw}"
                break
    elif name.startswith("weekly-review"):
        quotes = [l for l in body.split("\n") if l.startswith(">")]
        cand, rule = "\n".join(quotes), "周报导语"

    if not cand.strip():
        rule = "首个正文段落"
        for min_len in (40, 20):
            for para in paragraphs(body):
                if not para or len(para) < min_len:
                    continue
                if LABEL_RE.match(para) and len(para) < 30:
                    continue
                # 元信息行（IDE: xxx | Agent: yyy、适用于…、版本…）不是摘要
                if " | " in para and len(para) < 90:
                    continue
                if re.match(r"^(适用于|适配|环境|技术栈|版本|发布日期|作者|标签|日期)[:：]", para):
                    continue
                if re.match(r"^[A-Za-z][A-Za-z0-9 .]{1,14}[:：]", para):
                    continue
                # 有序列表项（"1. 下载安装: ..."）是步骤，不是摘要
                if re.match(r"^\d+[.、)]\s*", para):
                    continue
                # 表格行 / 元信息行
                if para.lstrip().startswith("|"):
                    continue
                if re.match(r"^(数据来源|数据为|本文|注：|更新时间|采集时间|来源：)", para):
                    continue
                if para.startswith("#"):
                    continue
                cand = para
                break
            if cand.strip():
                break

    pool = _sentences(cand) if cand else []
    if not pool:
        pool = _sentences(body)

    def build(allow_boilerplate: bool) -> str:
        acc = ""
        for sentence in pool:
            if "暂无摘要" in sentence or sentence.startswith("Generated by"):
                continue
            if re.match(r"^(本期覆盖|周报只回读|数据为|数据来源)", sentence):
                continue
            if not allow_boilerplate and _is_boilerplate(sentence, freq):
                continue
            if acc and acc[-1] not in "。！？；.!?;）)":
                acc = acc + "；" + sentence
            else:
                acc = (acc + sentence).strip()
            if len(acc) >= TARGET_MIN:
                break
        return acc

    acc = build(False) or build(True)
    if len(acc) < 20:
        return "", rule

    # 日报：把"1. xxx；2. yyy"拼成可读摘要
    if name.startswith("daily-"):
        items = []
        for x in acc.split("；"):
            item = re.sub(r"^\d+[.、)]\s*", "", x).strip()
            # 条目名之外的辅助行（为什么值得看/链接/热度/来源）不是"精选标题"
            if re.match(r"^(为什么值得看|链接|热度|来源)[:：]", item):
                continue
            if item.startswith("http"):
                continue
            if item:
                items.append(item)
        if items:
            acc = "今日精选：" + "、".join(items[:3])

    # 连载：标题里有版本号，带上它才知道说的是哪个版本
    if "-update-" in name and title:
        acc = f"{clean(title)}：{acc}"

    return _truncate(acc), rule

def _sentences(body: str) -> list[str]:
    """把正文切成干净句子（保留顺序，去重不在此处理）。"""
    out: list[str] = []
    for line in FENCE_RE.sub("", body).split("\n"):
        line = QUOTE_RE.sub("", BULLET_RE.sub("", line.strip()))
        if HEADING_RE.match(line):
            continue
        line = clean(line)
        if len(line) < 8:
            continue
        for part in SENT_SPLIT.split(line):
            part = part.strip(" -—·")
            if len(part) >= 8:
                out.append(part)
    return out


def _is_boilerplate(sentence: str, freq: collections.Counter) -> bool:
    total = freq.get("__total__", 1)
    return freq.get(sentence, 0) / max(total, 1) >= BOILERPLATE_RATIO


def _truncate(text: str) -> str:
    text = text.strip(" -—·")
    if len(text) <= TARGET_MAX:
        return text
    cut = text[:TARGET_MAX]
    for m in SENT_SPLIT.finditer(text[: TARGET_MAX + 20]):
        if m.end() <= TARGET_MAX:
            cut = text[: m.end()]
    if cut[-1] not in "。！？；":
        cut = cut.rstrip("，、,;；:： ") + "…"
    return cut


def fm_get(fm: str, key: str) -> str | None:
    m = re.search(rf"^{key}:\s*(.+?)\s*$", fm, re.M)
    return m.group(1).strip().strip("'\"") if m else None


def insert_description(text: str, desc: str) -> str:
    escaped = desc.replace("\\", "\\\\").replace('"', '\\"')
    line = f'description: "{escaped}"'
    m = FM_RE.match(text)
    fm, body = m.group(1), text[m.end():]
    lines = fm.split("\n")
    if any(l.startswith("description:") for l in lines):
        lines = [line if l.startswith("description:") else l for l in lines]
    else:
        anchor = next((i for i, l in enumerate(lines) if l.startswith("draft:")), 1)
        lines.insert(anchor + 1, line)
    return "---\n" + "\n".join(lines) + "\n---\n" + body


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true")
    ap.add_argument("--overwrite", action="store_true", help="连已有的 description 一起重写（默认保留手写）")
    ap.add_argument("--samples", type=int, default=12)
    args = ap.parse_args()

    files = sorted(POSTS.glob("*.md"))
    texts = {p: p.read_text(encoding="utf-8") for p in files}

    # 统计候选句频次（用于识别模板句）
    freq: collections.Counter = collections.Counter()
    freq["__total__"] = len(files)
    for p, t in texts.items():
        body = t[FM_RE.match(t).end():] if FM_RE.match(t) else t
        for sentence in _sentences(body):
            freq[sentence] += 1

    texts_titles = {
        p.name: (FM_RE.match(t).group(1) if FM_RE.match(t) else "")
        for p, t in texts.items()
    }

    results = []
    for p, t in texts.items():
        m = FM_RE.match(t)
        fm = m.group(1)
        existing = fm_get(fm, "description")
        body = t[m.end():]
        if existing and not args.overwrite:
            results.append((p, existing, "已有(保留)", True))
            continue
        cand, rule = pick_candidate(p, body, freq, fm_get(fm, "title") or "")
        if not cand:
            cand, rule = fm_get(fm, "title") or p.stem, "兜底:标题"
        results.append((p, cand, rule, existing is not None))

    # 描述去重：连载类常出现"同一条更新说明"，用标题前缀区分
    seen: collections.Counter = collections.Counter()
    deduped = []
    for p, d, rule, had in results:
        if d and not had and len(d) < TARGET_MIN and not d.startswith("今日精选") and not p.name.startswith("daily-"):
            title = fm_get(FM_RE.match(texts[p]).group(1), "title") or p.stem
            d = _truncate(f"{clean(title)}：{d}")
        if d and seen[d] and not had:
            title = fm_get(FM_RE.match(texts[p]).group(1), "title") or p.stem
            d = _truncate(f"{clean(title)}：{d}")
        seen[d] += 1
        deduped.append((p, d, rule, had))
    results = deduped

    by_rule = collections.Counter(r[2] for r in results)
    dup = len(results) - len({r[1] for r in results})
    print(f"重复描述: {dup}")
    empty = [r for r in results if not r[1]]
    too_short = [r for r in results if r[1] and len(r[1]) < TARGET_MIN]

    print(f"篇数: {len(results)}")
    print("规则分布:", dict(by_rule))
    print(f"空描述: {len(empty)}   短于 {TARGET_MIN} 字: {len(too_short)}")
    print("\n抽样:")
    for p, d, rule, had in results[: args.samples]:
        print(f"  [{rule}] {p.name}\n    → {d[:110]}")
    print(f"\n平均长度: {sum(len(r[1]) for r in results) / max(len(results),1):.1f} 字")

    if not args.apply:
        print("\n(dry-run，未修改；加 --apply 生效)")
        return 0

    changed = 0
    for p, d, rule, _ in results:
        t = texts[p]
        new = insert_description(t, d)
        if new != t:
            p.write_text(new, encoding="utf-8")
            changed += 1
    print(f"\n已写入 {changed} 个文件")

    # 幂等性
    again = 0
    for p, d, _, _ in results:
        t = p.read_text(encoding="utf-8")
        if insert_description(t, d) != t:
            again += 1
    print(f"幂等性检查: 二次运行变更数 = {again}（应为 0）")
    return 0 if again == 0 else 3


if __name__ == "__main__":
    raise SystemExit(main())
