#!/usr/bin/env bash
# P3 元数据/结构化数据校验（可作 CI 断言）
#
#   bash scripts/verify-meta.sh --dir <hugo 构建目录>
#   VNU_JAR=/path/vnu.jar bash scripts/verify-meta.sh --dir <dir>   # 追加 W3C 校验（0 error）
#
# 校验项（全部机器判定，不依赖人工判断）：
#   1. <html lang> = zh-cn
#   2. 每篇文章恰好 1 个 BlogPosting，inLanguage=zh-cn、无 articleBody/wordCount、author 为对象且 name 为字符串
#   3. canonical 自指（percent-decode 后比较）
#   4. og:image 存在且对应文件在构建产物中
#   5. meta description 非空、>=40 字、无模板残留
#   6. 文章页 HTML 体积中位数 <= 40KB
#   7. 可选：vnu 0 error
set -uo pipefail

DIR=""; SAMPLE=12
while [[ $# -gt 0 ]]; do
  case "$1" in
    --dir) DIR="$2"; shift 2 ;;
    --sample) SAMPLE="$2"; shift 2 ;;
    *) echo "未知参数: $1" >&2; exit 2 ;;
  esac
done
[[ -z "$DIR" ]] && { echo "用法: $0 --dir <build> [--sample N]" >&2; exit 2; }
[[ -d "$DIR" ]] || { echo "目录不存在: $DIR" >&2; exit 2; }

fail=0
pass() { printf '  ✅ %s\n' "$*"; }
bad()  { printf '  ❌ %s\n' "$*"; fail=$((fail+1)); }
say()  { printf '%s\n' "$*"; }

# macOS 自带 bash 3.2 没有 mapfile，用数组 + while read
POSTS=()
while IFS= read -r f; do POSTS+=("$f"); done < <(find "$DIR/posts" -name index.html -not -path '*/page/*' | sort)
[[ ${#POSTS[@]} -eq 0 ]] && { echo "没有找到文章页" >&2; exit 2; }
say "文章页数: ${#POSTS[@]}"

step=$(( ${#POSTS[@]} / SAMPLE )); [[ $step -lt 1 ]] && step=1
PICKED=()
while IFS= read -r f; do PICKED+=("$f"); done < <(printf '%s\n' "${POSTS[@]}" | awk -v s=$step 'NR%s==1' | head -"$SAMPLE")
say "抽样页数: ${#PICKED[@]}"

say "== 1. <html lang>"
langbad=0
for f in "${PICKED[@]}"; do
  grep -qE '<html[^>]*lang=zh-cn' "$f" || { langbad=$((langbad+1)); echo "    $f"; }
done
[[ $langbad -eq 0 ]] && pass "全部 lang=zh-cn" || bad "$langbad 页 lang 不是 zh-cn"

say "== 2. 结构化数据 + canonical"
if python3 - "$DIR" "${PICKED[@]}" <<'PY'
import json, re, sys
from pathlib import Path
from urllib.parse import unquote

build = Path(sys.argv[1]); files = list(map(Path, sys.argv[2:]))
problems = []
for f in files:
    html = f.read_text(encoding="utf-8", errors="replace")
    postings = []
    for raw in re.findall(r'<script type=application/ld\+json>(.*?)</script>', html, re.S):
        try:
            d = json.loads(raw)
        except json.JSONDecodeError:
            problems.append(f"{f}: JSON-LD 语法错误"); continue
        if isinstance(d, dict) and d.get("@type") == "BlogPosting":
            postings.append(d)
    if len(postings) != 1:
        problems.append(f"{f}: BlogPosting 数量={len(postings)}"); continue
    p = postings[0]
    if p.get("inLanguage") != "zh-cn": problems.append(f"{f}: inLanguage={p.get('inLanguage')!r}")
    if "articleBody" in p: problems.append(f"{f}: 仍含 articleBody")
    if "wordCount" in p: problems.append(f"{f}: 仍含 wordCount")
    author = p.get("author")
    if not (isinstance(author, dict) and isinstance(author.get("name"), str)):
        problems.append(f"{f}: author 结构异常 {author!r}")
    if len(str(p.get("description", ""))) > 200: problems.append(f"{f}: JSON-LD description 过长")
    if not p.get("image"): problems.append(f"{f}: JSON-LD 缺 image")

    rel = unquote(str(f.relative_to(build)).replace("/index.html", ""))
    m = re.search(r'<link rel=canonical href="?([^" >]+)', html)
    canon = unquote(m.group(1)).rstrip("/") if m else ""
    if not m or not canon.endswith(rel):
        problems.append(f"{f}: canonical 非自指 ({canon or 'none'})")

print("\n".join("    " + x for x in problems) if problems else "  ✅ 结构化数据与 canonical 全部合规")
sys.exit(1 if problems else 0)
PY
then :; else fail=$((fail+1)); fi

say "== 3. og:image"
if python3 - "$DIR" "${PICKED[@]}" <<'PY'
import sys
from pathlib import Path
from urllib.parse import unquote, urlparse
import re

build = Path(sys.argv[1]); bad = []
for f in map(Path, sys.argv[2:]):
    html = f.read_text(encoding="utf-8", errors="replace")
    m = re.search(r'og:image"?\s+content="?([^" >]+)', html)
    if not m:
        bad.append(f"缺 og:image: {f.relative_to(build)}"); continue
    path = unquote(urlparse(m.group(1)).path).lstrip("/")
    if not (build / path).exists():
        bad.append(f"og:image 文件不存在: {path}")
print("\n".join("    " + x for x in bad) if bad else "  ✅ og:image 均存在且文件可访问")
sys.exit(1 if bad else 0)
PY
then :; else fail=$((fail+1)); fi

say "== 4. meta description 质量"
if python3 - "${PICKED[@]}" <<'PY'
import re, sys
from pathlib import Path

bad = []
for f in map(Path, sys.argv[1:]):
    html = f.read_text(encoding="utf-8", errors="replace")
    m = re.search(r'<meta name=description content="([^"]*)"', html)
    d = m.group(1).strip() if m else ""
    if len(d) < 40:
        bad.append(f"{f.name}: 过短({len(d)}) {d[:40]}")
    for junk in ("暂无摘要", "Generated by", "官方动态优先 + 社区热度筛选版"):
        if junk in d:
            bad.append(f"{f.name}: 含模板残留 {junk!r}")
print("\n".join("    " + x for x in bad) if bad else "  ✅ description 长度与内容合规")
sys.exit(1 if bad else 0)
PY
then :; else fail=$((fail+1)); fi

say "== 5. 文章页 HTML 体积（中位数 <= 40KB）"
median=$(python3 - "${POSTS[@]}" <<'PY'
import os, statistics, sys
print(int(statistics.median([os.path.getsize(f) for f in sys.argv[1:]])))
PY
)
if [[ "$median" -le 40960 ]]; then pass "中位 ${median}B <= 40960B"; else bad "中位 ${median}B 超预算"; fi

if [[ -n "${VNU_JAR:-}" && -f "${VNU_JAR:-}" ]]; then
  say "== 6. W3C vnu（0 error）"
  VNU_OUT="$(mktemp)"
  java -jar "$VNU_JAR" --skip-non-html --format json "$DIR" >/dev/null 2>"$VNU_OUT"
  if python3 - "$VNU_OUT" <<'PY'
import collections, json, sys
d = json.load(open(sys.argv[1]))
msgs = d.get("messages", [])
errs = [m for m in msgs if m.get("type") == "error"]
if errs:
    print(f"  ❌ {len(errs)} 个 error")
    for m in errs[:5]:
        print("    -", m.get("message", "")[:100])
    sys.exit(1)
warn = collections.Counter(m.get("message", "")[:60] for m in msgs if m.get("type") == "info")
top = "; ".join(f"{v}× {k[:38]}" for k, v in warn.most_common(3))
print(f"  ✅ 0 error（{len(msgs)} 条 info/warning：{top}）")
PY
  then :; else fail=$((fail+1)); fi
  rm -f "$VNU_OUT"
else
  say "== 6. W3C vnu 跳过（未设置 VNU_JAR）"
fi

echo
if [[ "$fail" -eq 0 ]]; then say "✅ 元数据校验通过"; else say "❌ 元数据校验失败：$fail 项"; fi
exit $(( fail > 0 ))
